/**
 * Generates `src/styles/shiki.css` from the Shiki theme used in `astro.config.mjs`.
 * Run with `npm run assets:shiki` whenever the theme changes. The output is committed so
 * builds stay deterministic and the strict style-src CSP keeps working.
 */
import { writeFileSync } from 'node:fs';
import { bundledThemes } from 'shiki';

const THEME = 'github-light-high-contrast';

const loader = bundledThemes[THEME];
if (!loader) throw new Error(`Unknown Shiki theme: ${THEME}`);
const theme = (await loader()).default;

const colours = new Set();
const add = (value) => {
  if (typeof value === 'string' && /^#[0-9a-f]{3,8}$/i.test(value))
    colours.add(value.toLowerCase());
};
add(theme.fg);
add(theme.colors?.['editor.foreground']);
for (const token of theme.tokenColors ?? []) add(token.settings?.foreground);
for (const token of theme.settings ?? []) add(token.settings?.foreground);

const foreground = (theme.fg ?? theme.colors?.['editor.foreground'] ?? '#24292e').toLowerCase();

// Code blocks sit on a white surface (see global.css). Any palette colour that would fall below
// the WCAG AA 4.5:1 ratio against white is replaced with the theme foreground so highlighted
// tokens never reduce readability.
const luminance = (hex) => {
  const channel = (value) => (value <= 0.03928 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4);
  const full =
    hex.length === 4 ? `#${hex[1]}${hex[1]}${hex[2]}${hex[2]}${hex[3]}${hex[3]}` : hex.slice(0, 7);
  const [r, g, b] = [1, 3, 5].map((i) => channel(parseInt(full.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrastOnWhite = (hex) => 1.05 / (luminance(hex) + 0.05);
const accessible = (hex) => (contrastOnWhite(hex) >= 4.5 ? hex : foreground);

const lines = [
  `/* Generated by scripts/generate-shiki-css.mjs from the Shiki "${THEME}" theme. Do not edit by hand. */`,
  `.astro-code { color: ${foreground}; }`,
  `.sh-italic { font-style: italic; }`,
  `.sh-bold { font-weight: 700; }`,
  `.sh-underline { text-decoration: underline; }`,
];
for (const colour of [...colours].sort()) {
  lines.push(`.sh-${colour.slice(1)} { color: ${accessible(colour)}; }`);
}
writeFileSync(new URL('../src/styles/shiki.css', import.meta.url), `${lines.join('\n')}\n`);
console.log(`Wrote src/styles/shiki.css with ${colours.size} colour classes.`);
